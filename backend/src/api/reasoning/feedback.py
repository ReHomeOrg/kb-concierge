"""Детектор быстрой оценки решения (#14): «помогло / не помогло».

ДЕТЕРМИНИРОВАННЫЙ (rules, не LLM): после оформления заявки/обращения предлагаем оценить,
а ответ распознаём здесь. Отказ-сигнал («не помогло») имеет приоритет над «помогло»
(подстрока). Срабатывает только на КОРОТКОЙ реплике-оценке — длинные сообщения с «помогло»
внутри (новый запрос) не перехватываем. Вход — маскированный текст (G3).
"""

from __future__ import annotations

_MAX_WORDS = 6

_POSITIVE = (
    "помогло",
    "спасибо, помог",
    "всё отлично",
    "все отлично",
    "отлично, спасибо",
    "супер",
    "класс",
    "решилось",
    "решено",
    "то что нужно",
)
_NEGATIVE = (
    "не помогло",
    "не помог",
    "не решил",
    "не сработал",
    "бесполезно",
    "плохо помог",
    "так и не",
    "не то",
)


def detect_feedback(masked_text: str) -> str | None:
    """Оценка решения: "negative" / "positive" / None (не оценка).

    Только короткая реплика (≤ 6 слов) — чтобы не перехватывать новый запрос со словом
    «помогло» внутри. Отказ проверяется первым (он содержит подстроку «помогло»).
    """
    text = masked_text.lower().strip()
    if len(text.split()) > _MAX_WORDS:
        return None
    if any(n in text for n in _NEGATIVE):
        return "negative"
    if any(p in text for p in _POSITIVE):
        return "positive"
    return None
